#ifndef LLVM_LIB_TARGET_ZODIAC_ZODIACSUBTARGET_H
#define LLVM_LIB_TARGET_ZODIAC_ZODIACSUBTARGET_H

#include "ZodiacFrameLowering.h"
#include "ZodiacISelLowering.h"
#include "ZodiacInstrInfo.h"
#include "ZodiacSelectionDAGInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/Target/TargetMachine.h"

#define GET_SUBTARGETINFO_HEADER
#include "ZodiacGenSubtargetInfo.inc"

namespace llvm {

class ZodiacSubtarget : public ZodiacGenSubtargetInfo {
public:
  // This constructor initializes the data members to match that
  // of the specified triple.
  ZodiacSubtarget(const Triple &TargetTriple, StringRef Cpu,
                 StringRef FeatureString, const TargetMachine &TM,
                 const TargetOptions &Options, CodeModel::Model CodeModel,
                 CodeGenOptLevel OptLevel);

  // ParseSubtargetFeatures - Parses features string setting specified
  // subtarget options.  Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  ZodiacSubtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);

  void initSubtargetFeatures(StringRef CPU, StringRef FS);

  bool enableMachineScheduler() const override { return true; }

  const ZodiacInstrInfo *getInstrInfo() const override { return &InstrInfo; }

  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }

  const ZodiacRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }

  const ZodiacTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  const ZodiacSelectionDAGInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

private:
  ZodiacInstrInfo InstrInfo;
  ZodiacFrameLowering FrameLowering;
  ZodiacTargetLowering TLInfo;
  ZodiacSelectionDAGInfo TSInfo;
};
} // namespace llvm

#endif // LLVM_LIB_TARGET_ZODIAC_ZODIACSUBTARGET_H
